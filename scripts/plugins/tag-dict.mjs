// 从一段文字（通常是「算法类型」那一行）推断规范标签
export function inferTags(text, max = 4) {
  const hits = []
  for (const [re, tag] of TAG_RULES) {
    if (!re.test(text)) continue
    if (!VOCABULARY.includes(tag)) continue
    if (hits.includes(tag)) continue
    hits.push(tag)
    if (hits.length >= max) break
  }
  return hits
}
